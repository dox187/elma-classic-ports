; Exact two-wheel brake spring and angular damping in bank8.
; ABI0 tq*: replace both signed32 torques. Bike is read-only here.
; Full wrapping angle subtraction precedes the signed8 shift; angular
; damping and spring results retain all 32 bits. No scratch RAM.
.module physics_brake_fast
.area _CODE_8
_riding_brake32::
 ld a,(#_riding_landing_contact)
 ld hl,#_Bike+40
 ld de,#_Bike+101
 call brake_one
 ldhl sp,#2
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 ld (hl),e
 inc hl
 ld (hl),d
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
 ld a,(#_riding_landing_contact+1)
 ld hl,#_Bike+64
 ld de,#_Bike+105
 call brake_one
 ldhl sp,#2
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 inc hl
 inc hl
 inc hl
 inc hl
 ld (hl),e
 inc hl
 ld (hl),d
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
 ret
; HL wheel.alfa, DE dbrake; signed32 result BCDE, low byte E.
brake_one:
 push af
 push hl
 ld h,d
 ld l,e
 ld a,(#_Bike+16)
 add a,(hl)
 ld e,a
 inc hl
 ld a,(#_Bike+17)
 adc a,(hl)
 ld d,a
 inc hl
 ld a,(#_Bike+18)
 adc a,(hl)
 ld c,a
 inc hl
 ld a,(#_Bike+19)
 adc a,(hl)
 ld b,a
 pop hl
 ld a,(hl+)
 sub a,e
 ld e,a
 ld a,(hl+)
 sbc a,d
 ld d,a
 ld a,(hl+)
 sbc a,c
 ld c,a
 ld a,(hl+)
 sbc a,b
 ld b,a
; HL now wheel.omega; preserve its address across exact coefficient call.
 push hl
 ld e,d
 ld d,c
 ld l,b
 ld a,b
 add a,a
 sbc a,a
 ld h,a
 push hl
 push de
 call _riding_coeff32_C_BRAKE_A
 add sp,#4
 push hl
 push de
 ldhl sp,#4
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 ld e,(hl)
 inc hl
 ld d,(hl)
 inc hl
 ld c,(hl)
 inc hl
 ld b,(hl)
 ld hl,#_Bike+20
 ld a,e
 sub a,(hl)
 ld e,a
 inc hl
 ld a,d
 sbc a,(hl)
 ld d,a
 inc hl
 ld a,c
 sbc a,(hl)
 ld c,a
 inc hl
 ld a,b
 sbc a,(hl)
 ld b,a
 ; Saved contact count is above the spring result and wheel pointer.
 ldhl sp,#7
 ld a,(hl)
 or a,a
 push bc
 push de
 jr z,brake_free_damping
 call _riding_coeff32_C_BRAKE_GW
 jr brake_damping_done
brake_free_damping:
 call _riding_coeff32_C_BRAKE_W
brake_damping_done:
 add sp,#4
 ld b,h
 ld c,l
 ldhl sp,#0
 ld a,(hl+)
 add a,e
 ld e,a
 ld a,(hl+)
 adc a,d
 ld d,a
 ld a,(hl+)
 adc a,c
 ld c,a
 ld a,(hl)
 adc a,b
 ld b,a
; -(spring+friction), with the same wrapping32 result as -spring-friction.
 xor a
 sub a,e
 ld e,a
 ld a,#0
 sbc a,d
 ld d,a
 ld a,#0
 sbc a,c
 ld c,a
 ld a,#0
 sbc a,b
 ld b,a
 add sp,#8
 ret
