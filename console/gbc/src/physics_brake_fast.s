; Exact two-wheel brake spring and angular damping in bank8.
; ABI0 tq*: replace both signed16 torques. Bike is read-only here.
; Full wrapping angle subtraction precedes the signed8 shift; omega
; subtraction is signed17 before clamping to +/-16383. No scratch RAM.
.module physics_brake_fast
.area _CODE_8
_riding_brake32::
 ld hl,#_Bike+38
 ld de,#_Bike+95
 call brake_one
 ldhl sp,#2
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 ld (hl),c
 inc hl
 ld (hl),b
 ld hl,#_Bike+60
 ld de,#_Bike+99
 call brake_one
 ldhl sp,#2
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 inc hl
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
 ret
; HL wheel.alfa, DE dbrake; signed16 result BC.
brake_one:
 push hl
 ld h,d
 ld l,e
 ld a,(#_Bike+16)
 add a,(hl)
 ld e,a
 inc hl
 ld a,(#_Bike+17)
 adc a,(hl)
 ld d,a
 inc hl
 ld a,(#_Bike+18)
 adc a,(hl)
 ld c,a
 inc hl
 ld a,(#_Bike+19)
 adc a,(hl)
 ld b,a
 pop hl
 ld a,(hl+)
 sub a,e
 ld e,a
 ld a,(hl+)
 sbc a,d
 ld d,a
 ld a,(hl+)
 sbc a,c
 ld c,a
 ld a,(hl+)
 sbc a,b
 ld b,a
; HL now wheel.omega; preserve its address across exact coefficient call.
 push hl
 ld e,d
 ld d,c
 ld l,b
 ld a,b
 add a,a
 sbc a,a
 ld h,a
 push hl
 push de
 call _riding_coeff32_C_BRAKE_A
 add sp,#4
 push hl
 push de
 ldhl sp,#4
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 ld e,(hl)
 inc hl
 ld d,(hl)
 ld a,d
 add a,a
 sbc a,a
 ld c,a
 ld a,(#_Bike+21)
 add a,a
 sbc a,a
 ld b,a
 ld a,(#_Bike+20)
 ld l,a
 ld a,(#_Bike+21)
 ld h,a
 ld a,e
 sub a,l
 ld e,a
 ld a,d
 sbc a,h
 ld d,a
 ld a,c
 sbc a,b
 bit 7,a
 jr nz,brake_negative
 ld a,d
 cp #0x40
 jr c,brake_clamped
 ld de,#0x3fff
 jr brake_clamped
brake_negative:
 ld a,d
 cp #0xc0
 jr c,brake_low
 jr nz,brake_clamped
 ld a,e
 or a
 jr nz,brake_clamped
brake_low:
 ld de,#0xc001
brake_clamped:
 push de
 call _riding_coeff16_C_BRAKE_W
 add sp,#2
 ld a,d
 add a,a
 sbc a,a
 ld b,a
 ld c,a
 ldhl sp,#0
 ld a,(hl+)
 add a,e
 ld e,a
 ld a,(hl+)
 adc a,d
 ld d,a
 ld a,(hl+)
 adc a,c
 ld c,a
 ld a,(hl)
 adc a,b
 ld b,a
; -(spring+friction), with the same wrapping32 result as -spring-friction.
 xor a
 sub a,e
 ld l,a
 ld a,#0
 sbc a,d
 ld h,a
 ld a,#0
 sbc a,c
 ld e,a
 ld a,#0
 sbc a,b
 ld d,a
 ld b,h
 ld c,l
 add sp,#6
 jp _sat16
