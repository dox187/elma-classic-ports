; DE = floor(13 * signed high byte / 2) + 3 + radius.
; Adding this to the world delta gives an unsigned interval [0,2*radius].
rider_box_bias:
 ld l,a
 ld e,a
 add a,a
 sbc a,a
 ld h,a
 ld d,a
 add hl,hl
 add hl,de
 add hl,hl
 add hl,hl
 add hl,de
 sra h
 rr l
 ld de,#3+rider_box_radius
 add hl,de
 ld d,h
 ld e,l
 ret
