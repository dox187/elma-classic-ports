 call rider_box_bias
 pop hl
 push hl
 add hl,de
 ld a,h
 or a,a
 jr nz,rider_local_project
 ld a,l
 cp #2*rider_box_radius+1
 jr nc,rider_local_project
 ld a,#1
 jr rider_local_return

