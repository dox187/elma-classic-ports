; Exact rolling response: ABI0 k*,contact*,dvx32,dvy32,tq32, bank9.
; Existing helpers preserve all projections, coefficient rounding and saturation.
; Local stack: tangent0..3, projected velocity4..7, torque/speed8..11.
; No shared scratch; circle_t offsets are compile-time checked by the caller.
.module physics_roll_fast
.area _CODE_9
_riding_roll32::
 add sp,#-12
; Tangent is (-ny,nx), with the original signed16 negation.
 ldhl sp,#16
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 ld c,(hl)
 inc hl
 ld b,(hl)
 inc hl
 ld e,(hl)
 inc hl
 ld d,(hl)
 xor a
 sub a,e
 ld e,a
 ld a,#0
 sbc a,d
 ld d,a
 ldhl sp,#0
 ld (hl),e
 inc hl
 ld (hl),d
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
; vn = dotq32(vx,vy,tangent,14).
 ldhl sp,#14
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 ld de,#8
 add hl,de
 ld d,h
 ld e,l
 ldhl sp,#0
 call _riding_dotq14_regs
 ld b,h
 ld c,l
 ldhl sp,#4
 ld (hl),e
 inc hl
 ld (hl),d
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
; dvn = dotq32(dvx,dvy,tangent,14).
 ldhl sp,#18
 ld d,h
 ld e,l
 ldhl sp,#0
 call _riding_dotq14_regs
 push hl
 push de
 call _riding_wheel_roll_t
 add sp,#4
; t = tq + coefficient(dvn), wrapping32.
 ld b,h
 ld c,l
 ldhl sp,#26
 ld a,(hl+)
 add a,e
 ld e,a
 ld a,(hl+)
 adc a,d
 ld d,a
 ld a,(hl+)
 adc a,c
 ld c,a
 ld a,(hl)
 adc a,b
 ld b,a
 ldhl sp,#8
 ld (hl),e
 inc hl
 ld (hl),d
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
; sp = vn + Q24(t,C_ROLL_DV), before angular quantization.
 ldhl sp,#10
 ld e,(hl)
 inc hl
 ld d,(hl)
 push de
 ldhl sp,#10
 ld e,(hl)
 inc hl
 ld d,(hl)
 push de
 call _riding_wheel_roll_dv
 add sp,#4
 ld b,h
 ld c,l
 ldhl sp,#4
 ld a,(hl+)
 add a,e
 ld e,a
 ld a,(hl+)
 adc a,d
 ld d,a
 ld a,(hl+)
 adc a,c
 ld c,a
 ld a,(hl)
 adc a,b
 ld b,a
 ldhl sp,#8
 ld (hl),e
 inc hl
 ld (hl),d
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
; omega = Q24(sp,C_ROLL_W); keep the full signed32 angular state.
 push bc
 push de
 call _riding_wheel_roll_w
 add sp,#4
 ld b,h
 ld c,l
 ldhl sp,#14
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 push de
 ld de,#20
 add hl,de
 pop de
 ld (hl),e
 inc hl
 ld (hl),d
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
; vx = mulq32(sp,tangent,14).
 ldhl sp,#0
 ld c,(hl)
 inc hl
 ld b,(hl)
 ldhl sp,#8
 call _riding_mulq14_regs
 ld b,h
 ld c,l
 ldhl sp,#14
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 push de
 ld de,#8
 add hl,de
 pop de
 ld (hl),e
 inc hl
 ld (hl),d
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
; vy = mulq32(sp,tangent,14).
 ldhl sp,#2
 ld c,(hl)
 inc hl
 ld b,(hl)
 ldhl sp,#8
 call _riding_mulq14_regs
 ld b,h
 ld c,l
 ldhl sp,#14
 ld a,(hl+)
 ld h,(hl)
 ld l,a
 push de
 ld de,#12
 add hl,de
 pop de
 ld (hl),e
 inc hl
 ld (hl),d
 inc hl
 ld (hl),c
 inc hl
 ld (hl),b
 ldhl sp,#14
 ld e,(hl)
 inc hl
 ld d,(hl)
 push de
 call _riding_wheel_move
 add sp,#14
