"""Production close-reaction division: native vs unbounded Python oracle.

The same assembly helper is linked into the game. Whole-physics parity tests
cover its call-site and zero-distance table fallback.
"""
import argparse, json, random, re, struct, subprocess
from pathlib import Path
from pyboy import PyBoy
BASE=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--random',type=int,default=6000)
p.add_argument('--out',type=Path,required=True)
args=p.parse_args()
if not 0<=args.random<=20000:p.error('--random must be in [0,20000]')
OUT=args.out.resolve();OUT.mkdir(parents=True,exist_ok=False)
rng=random.Random(0x96D1)
rows=[]; categories={}; row_categories=[]
def oracle(t,d):
    if not d:return 0
    q=(abs(t)<<22)//d
    if t<0:q=-q
    return min(2147483647,max(-2147483648,q))
def add(t,d,category):
    rows.append((t,d,oracle(t,d))); row_categories.append(category)
    categories[category]=categories.get(category,0)+1
limits=[-2147483648,-2147483647,-1073741825,-1073741824,-65537,-32768,-513,-512,-511,-3,-2,-1,0,1,2,3,511,512,513,32767,65536,1073741823,1073741824,2147483646,2147483647]
denominators=[0,1,2,3,7,31,255,256,511,512,513,1023,1024,1025,65535,65536,65537,82021,131071,131072,131073,2147483647,2147483648,2147483649,4294967293,4294967294,4294967295]
for t in limits:
    for d in denominators:add(t,d,'edges')
# Probe the exact signed saturation threshold, including negative nonmultiples.
for d in denominators[1:]:
    threshold=(2147483648*d)//4194304
    for t in range(max(0,threshold-3),min(2147483648,threshold+4)):
        add(t,d,'saturation_threshold');add(-t,d,'saturation_threshold')
# Signed16 coordinate squares exercise the actual integration denominator.
coords=[-32768,-32767,-1024,-367,-287,-256,-16,-1,0,1,16,255,287,367,1024,32766,32767]
for x in coords:
    for y in coords:
        for t in [-32768,-1,1,32767]:add(t,x*x+y*y,'coordinate_edges')
for i in range(args.random):
    t=rng.randint(-2147483648,2147483647)
    d=rng.randint(1,4294967295)
    add(t,d,'random_full')
    # Realistic small torque and close-compression separation, independently
    # random rather than generated by any assembly intermediate.
    x=rng.randint(-367,367);y=rng.randint(-367,367)
    add(rng.randint(-32768,32767),x*x+y*y,'random_close')
# Deterministic negative truncation: exact result -1398101, not -1398102.
add(-1,3,'negative_nonintegral')
for t,x,y in [(-41776,-287,21),(41578,284,20)]:
    add(t,x*x+y*y,'captured_impact')
(OUT/'vectors.json').write_text(json.dumps(rows)+'\n')
header='#include <stdint.h>\ntypedef struct{int32_t t;uint32_t d;int32_t expected;}vec_t;\n'
sources=[]
for bank,start in enumerate(range(0,len(rows),1000),10):
    block=rows[start:start+1000]
    header+=f'extern const vec_t vecs{bank}[];\n#define N{bank} {len(block)}\n'
    source=OUT/f'vecs{bank}.c'
    # Hex literals avoid compiler-specific handling of the -2147483648 token.
    source.write_text(f'#pragma bank {bank}\n#include "vectors.h"\nconst vec_t vecs{bank}[]={{\n'+',\n'.join('{'+f'0x{t&0xffffffff:08x}UL,0x{d:08x}UL,0x{q&0xffffffff:08x}UL'+'}'for t,d,q in block)+'\n};\n')
    sources.append((bank,source))
(OUT/'vectors.h').write_text(header)
driver='''#include <gb/gb.h>
#include <gb/cgb.h>
#include <string.h>
#include "vectors.h"
int32_t riding_close_reaction32(int32_t,uint32_t)__sdcccall(0);
volatile uint8_t done;
volatile uint16_t failures,count,banks_bad;
volatile int32_t actual,first_actual,first_expected,first_t;
volatile uint32_t first_d;
vec_t copy;
void check(void){
 SWITCH_ROM(8);actual=riding_close_reaction32(copy.t,copy.d);
 if(CURRENT_BANK!=8)++banks_bad;
 if(actual!=copy.expected){if(!failures){first_actual=actual;first_expected=copy.expected;first_t=copy.t;first_d=copy.d;}++failures;}
 ++count;
}
void main(void){uint16_t i;disable_interrupts();DISPLAY_OFF;cpu_fast();
'''
for bank,_ in sources:driver+=f'for(i=0;i<N{bank};++i){{SWITCH_ROM({bank});memcpy(&copy,&vecs{bank}[i],sizeof(copy));check();}}\n'
driver+='done=1;while(1){}}\n'
(OUT/'driver.c').write_text(driver)
cmd=[BASE/'.toolchain/gbdk/bin/lcc','-msm83:gb','-Wf--opt-code-size','-Wf--max-allocs-per-node','-Wf100000','-Wm-yC','-Wm-yt0x19','-Wm-yoA','-Wl-m','-Wl-j','-I'+str(OUT),'-o',OUT/'check.gbc',OUT/'driver.c',BASE/'src/physics_reaction_division.s',*[v for _,v in sources]]
r=subprocess.run(list(map(str,cmd)),capture_output=True,text=True)
(OUT/'compile.log').write_text(r.stdout+r.stderr)
assert r.returncode==0,(OUT/'compile.log').read_text()
symbols={k:int(v,16)for k,v in re.findall(r'DEF (_\w+) 0x([0-9A-Fa-f]+)',(OUT/'check.noi').read_text())}
emu=PyBoy(str(OUT/'check.gbc'),window='null',sound_emulated=False,cgb=True);emu.set_emulation_speed(0)
cycles=[];pending=[];returns=set();bad_sp=[];bad_args=[]
def returned(_):
    if pending:
        sp,when,original_args=pending.pop()
        if bytes(emu.memory[sp+2:sp+10])!=original_args:bad_args.append(len(cycles))
        if emu.register_file.SP!=sp+2:bad_sp.append((sp,emu.register_file.SP))
        cycles.append(emu._cycles()-when)
def entered(_):
    sp=emu.register_file.SP;pc=emu.memory[sp]+256*emu.memory[sp+1]
    if pc not in returns:emu.hook_register(0,pc,returned,None);returns.add(pc)
    pending.append((sp,emu._cycles(),bytes(emu.memory[sp+2:sp+10])))
emu.hook_register(8,symbols['_riding_close_reaction32']&65535,entered,None)
try:
    for _ in range(500):
        emu.tick(50,False)
        if emu.memory[symbols['_done']]:break
    def n(name,size=2,signed=False):return int.from_bytes(bytes(emu.memory[symbols['_'+name]:symbols['_'+name]+size]),'little',signed=signed)
    report={name:n(name)for name in('failures','count','banks_bad')}
    report.update(done=n('done',1),expected_cases=len(rows),categories=categories,stack_mismatches=bad_sp,argument_corruption=bad_args,code_bytes=symbols['_riding_close_reaction32_end']-symbols['_riding_close_reaction32'],cycles={'min':min(cycles),'max':max(cycles),'mean':sum(cycles)/len(cycles),'count':len(cycles)})
    report['first_failure']={name:n('first_'+name,4,name!='d')for name in('t','d','actual','expected')}
    report['coverage']={'zero_denominator':sum(d==0 for t,d,q in rows),'positive_saturation':sum(d!=0 and (t<<22)//d>2147483647 for t,d,q in rows),'negative_saturation':sum(d!=0 and t<0 and (abs(t)<<22)//d>2147483648 for t,d,q in rows),'negative_nonintegral':sum(d!=0 and t<0 and ((abs(t)<<22)%d)!=0 for t,d,q in rows),'unsigned_denominator_high_bit':sum(d>=2147483648 for t,d,q in rows)}
    report['cycles_by_category']={}
    for category in categories:
        vals=[cycles[i]for i,c in enumerate(row_categories)if c==category and i<len(cycles)]
        if vals:report['cycles_by_category'][category]={'min':min(vals),'max':max(vals),'mean':sum(vals)/len(vals)}
    report['captured_impact']=[dict(torque=t,distance2=d,result=q,cycles=cycles[i])for i,(t,d,q)in enumerate(rows)if row_categories[i]=='captured_impact' and i<len(cycles)]
    (OUT/'cycles.json').write_text(json.dumps(cycles)+'\n')
    (OUT/'report.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))
    assert report['done'] and report['count']==len(rows) and len(cycles)==len(rows) and not report['failures'] and not report['banks_bad'] and not bad_sp and not bad_args
finally:emu.stop(save=False)
