"""Generate certified world-space strips for the scheduled rider constraint."""
import argparse
import re
from pathlib import Path

from physics_sine import interpolate, read_sintab


def rotate(x, y, quadrant):
    return ((x, y), (y, -x), (-x, -y), (-y, x))[quadrant]


def coefficients(header):
    text = header.read_text()
    constants = dict((n, int(v)) for n, v in re.findall(
        r"^#define (SEAT_[XY]|RIDER_(?:TOP|LEFT|RIGHT)) (-?\d+)$", text, re.M))
    profiles = []
    legacy = []
    for name in ("C_SEAT_NX", "C_SEAT_NY", "C_ELLIPSE"):
        match = re.search(r"q24_" + name + r"\[2\]\s*=\s*\{([^}]+)\}", text)
        if not match:
            raise ValueError(f"Scheduled coefficients required for {name}")
        profiles.append([int(v) for v in match[1].split(",")])
        mantissa, exponent = (int(re.search(rf"^#define {name}_{part} (\d+)$", text, re.M)[1])
                              for part in ("M", "E"))
        legacy.append(mantissa << (24 - exponent))
    return constants, set(zip(*profiles)) | {tuple(legacy)}


def product_bounds(left, right):
    values = [x * y for x in left for y in right]
    return min(values), max(values)


def safe_strip(u, v, trig, constants, profiles):
    # Bound each dot over all corners and coefficient pairs in this slice.
    cs, sn = trig
    cu, sv = product_bounds(cs, u), product_bounds(sn, v)
    cv, su = product_bounds(cs, v), product_bounds(sn, u)
    x = (max(abs(cu[0] + sv[0]), abs(cu[1] + sv[1])) + 8192) >> 14
    ymin, ymax = (cv[0] - su[1] + 8192) >> 14, (cv[1] - su[0] + 8192) >> 14
    top = constants["RIDER_TOP"]
    if -x < constants["RIDER_LEFT"] or x > constants["RIDER_RIGHT"] or ymax > top:
        return False

    def scaled(n, scale):
        return (n * scale + (1 << 23)) >> 24

    sx, sy = constants["SEAT_X"], constants["SEAT_Y"]
    for nx, ny, ellipse in profiles:
        if min(nx, ny, ellipse) <= 0:
            raise ValueError("Seat and ellipse factors must be positive")
        under = scaled(ymin - sy, ny) - scaled(x - sx, nx)
        over = scaled(ymax - sy, ny) - scaled(-x - sx, nx)
        if under < 0 or over > 32767:
            return False
        if scaled(x, ellipse) ** 2 + max(0, ymax) ** 2 > top ** 2:
            return False
    return True


def generate(sine_source, header):
    constants, profiles = coefficients(header)
    sine = read_sintab(sine_source)
    samples = [set() for _ in range(32)]
    for phase in range(65536):
        octant = phase >> 13
        quadrant = ((phase + 8192) >> 14) & 3
        c, s = rotate(interpolate(sine, phase + 16384), interpolate(sine, phase), quadrant)
        index = (phase >> 8) & 31
        if octant & 1:
            index, s = 31 - index, -s
        samples[index].add((c, s))

    rows = []
    for group in samples:
        c, s = zip(*group)
        bounds = (min(c), max(c)), (min(s), max(s))
        cells = []
        for ix in range(64):
            x = ix * 16 - 512
            ys = [iy for iy in range(256)
                  if safe_strip((x, x + 15), (iy * 2, iy * 2 + 1),
                                bounds, constants, profiles)]
            # Rounding may leave a hole at a strip tip. Retain the longest
            # contiguous certified run instead of joining across the gap.
            runs = []
            for y in ys:
                if not runs or y != runs[-1][1] + 1:
                    runs.append([y, y])
                else:
                    runs[-1][1] = y
            cells.append(max(runs, key=lambda r: r[1] - r[0]) if runs else [255, 0])
        active = [i for i, pair in enumerate(cells) if pair[0] <= pair[1]]
        first, last = (active[0], active[-1] + 1) if active else (0, 0)
        rows.append((first, cells[first:last]))
    return rows


def assembly(rows):
    lines = ["; Generated by tools/rider_clearance.py. Each row stores the first",
             "; transverse bin, its count and inclusive vertical bins (two units each).",
             "rider_strip_directory:"]
    for i in range(0, len(rows), 8):
        lines.append(" .dw " + ",".join(f"rider_strip_{j}" for j in range(i, i + 8)))
    for i, (origin, pairs) in enumerate(rows):
        lines += [f"rider_strip_{i}:", f" .db {origin},{len(pairs)}"]
        for j in range(0, len(pairs), 12):
            lines.append(" .db " + ",".join(str(value) for pair in pairs[j:j+12] for value in pair))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sine-source", type=Path, required=True)
    parser.add_argument("--constants", type=Path, required=True)
    args = parser.parse_args()
    print(assembly(generate(args.sine_source, args.constants)), end="")
