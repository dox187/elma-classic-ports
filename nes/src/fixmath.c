uint16_t isqrt32( uint32_t a ) {
	uint32_t res = 0, bit = 1ul << 30;
	while( bit > a )
		bit >>= 2;
	while( bit ) {
		if( a >= res+bit ) {
			a -= res+bit;
			res = (res >> 1)+bit;
		}
		else
			res >>= 1;
		bit >>= 2;
	}
	return (uint16_t)res;
}

// For the rare cases of physics.S:
int16_t div14( int16_t x, int16_t l ) {
	return (int16_t)(((int32_t)x << 14)/l);
}

int16_t muldiv( int16_t x, int16_t m, int16_t d ) {
	return (int16_t)(mul16( x, m )/d);
}
