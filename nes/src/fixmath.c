int16_t fsin( uint16_t a ) {
	uint8_t i = a >> 8, f = a & 0xff;
	int16_t s0 = Sintab[i];
	return s0 + (int16_t)(mul16( Sintab[i+1]-s0, f ) >> 8);
}

int16_t fcos( uint16_t a ) {
	return fsin( a + 16384 );
}

